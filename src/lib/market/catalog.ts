function normalizeText(text: string) {
  return text.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
}

/** Offline search over the catalog (symbol prefix first, then name matches). */
export function searchCatalog(query: string, limit = 12): CatalogEntry[] {
  const q = normalizeText(query.trim());
  if (!q) return [];
  const scored: { entry: CatalogEntry; score: number }[] = [];
  for (const entry of CATALOG) {
    const sym = entry.symbol.toLowerCase();
    const name = normalizeText(entry.name);
    let score = 0;
    if (sym === q) score = 100;
    else if (sym.startsWith(q)) score = 80;
    else if (name.startsWith(q)) score = 70;
    else if (name.includes(q)) score = 50;
    else if (sym.includes(q)) score = 40;
    if (score > 0) scored.push({ entry, score });
  }
  return scored
    .sort((a, b) => b.score - a.score || a.entry.symbol.localeCompare(b.entry.symbol))
    .slice(0, limit)
    .map((s) => s.entry);
}
