type Seed = Omit<CatalogEntry, "type" | "currency" | "exchange" | "session"> &
  Partial<Pick<CatalogEntry, "type" | "currency" | "exchange" | "session">>;

const us = (e: Seed): CatalogEntry => ({ type: "EQUITY", currency: "USD", exchange: "NASDAQ", session: "US", country: "États-Unis", ...e });
const nyse = (e: Seed): CatalogEntry => us({ exchange: "NYSE", ...e });
const paris = (e: Seed): CatalogEntry => ({
  type: "EQUITY",
  currency: "EUR",
  exchange: "Euronext Paris",
  session: "EU",
  country: "France",
  pea: true,
  ...e,
});
const eu = (e: Seed): CatalogEntry => ({ type: "EQUITY", currency: "EUR", session: "EU", exchange: "Europe", pea: true, ...e });
const etf = (e: Seed): CatalogEntry => ({ type: "ETF", currency: "EUR", exchange: "Euronext Paris", session: "EU", ...e });
const index = (e: Seed): CatalogEntry => ({ type: "INDEX", exchange: "Indice", ...e }) as CatalogEntry;
const fx = (symbol: string, name: string, price: number): CatalogEntry => ({
  symbol,
  name,
  type: "CURRENCY",
  currency: symbol.slice(3, 6),
  exchange: "Devises",
  session: "FX",
  price,
  vol: 0.07,
  drift: 0,
});
const future = (symbol: string, name: string, price: number, vol: number, currency = "USD"): CatalogEntry => ({
  symbol,
  name,
  type: "FUTURE",
  currency,
  exchange: "Contrats à terme",
  session: "FUT",
  price,
  vol,
  drift: 0.02,
});
const crypto = (symbol: string, name: string, price: number, vol: number, drift: number): CatalogEntry => ({
  symbol,
  name,
  type: "CRYPTOCURRENCY",
  currency: symbol.split("-")[1] ?? "USD",
  exchange: "Crypto",
  session: "CRYPTO",
  price,
  vol,
  drift,
  sector: "Crypto-actifs",
  country: "Monde",
});

