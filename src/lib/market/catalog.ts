/** Best-effort exposure region of a fund from its name. */
export function regionFromName(name: string): string | undefined {
  const n = name.toLowerCase();
  if (/(all[- ]world|acwi|monde|world|global)/.test(n)) return "Monde";
  if (/(emerging|émergent|emergents|\bem\b)/.test(n)) return "Pays émergents";
  if (/(s&p|nasdaq|dow jones|russell|\bus\b|usa|america)/.test(n)) return "États-Unis";
  if (/(cac|france)/.test(n)) return "France";
  if (/(stoxx|europe|euro|emu)/.test(n)) return "Europe";
  if (/(japan|japon|nikkei|topix)/.test(n)) return "Japon";
  if (/(china|chine|hang seng)/.test(n)) return "Chine";
  if (/(india|inde)/.test(n)) return "Inde";
  if (/(gold|\bor\b|physical)/.test(n)) return "Monde";
  return undefined;
}

