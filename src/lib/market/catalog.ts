import type { AssetType } from "./types";

/**
 * Reference list of well-known instruments. It powers the offline search, the
 * benchmark and market lists, and the simulated data mode (anchor prices,
 * volatility and dividend profile are rough orders of magnitude, never quotes).
 */

export type SessionId = "US" | "EU" | "UK" | "CH" | "DK" | "JP" | "HK" | "CRYPTO" | "FX" | "FUT";

export interface Session {
  tz: string;
  /** Minutes after local midnight. */
  open: number;
  close: number;
  /** Trades every day of the week. */
  everyDay?: boolean;
}

export const SESSIONS: Record<SessionId, Session> = {
  US: { tz: "America/New_York", open: 9 * 60 + 30, close: 16 * 60 },
  EU: { tz: "Europe/Paris", open: 9 * 60, close: 17 * 60 + 30 },
  UK: { tz: "Europe/London", open: 8 * 60, close: 16 * 60 + 30 },
  CH: { tz: "Europe/Zurich", open: 9 * 60, close: 17 * 60 + 30 },
  DK: { tz: "Europe/Copenhagen", open: 9 * 60, close: 17 * 60 },
  JP: { tz: "Asia/Tokyo", open: 9 * 60, close: 15 * 60 + 30 },
  HK: { tz: "Asia/Hong_Kong", open: 9 * 60 + 30, close: 16 * 60 },
  CRYPTO: { tz: "UTC", open: 0, close: 24 * 60, everyDay: true },
  FX: { tz: "Europe/London", open: 0, close: 24 * 60 },
  FUT: { tz: "America/New_York", open: 0, close: 23 * 60 },
};

export interface CatalogEntry {
  symbol: string;
  name: string;
  type: AssetType;
  currency: string;
  exchange: string;
  session: SessionId;
  /** Anchor price used by the simulator. */
  price: number;
  /** Annualized volatility and drift used by the simulator. */
  vol: number;
  drift: number;
  divYield?: number;
  /** Months (1–12) in which dividends go ex. */
  divMonths?: number[];
  sector?: string;
  industry?: string;
  country?: string;
  website?: string;
  employees?: number;
  marketCap?: number;
  pe?: number;
  description?: string;
  /** Exposure region for funds/indices. */
  region?: string;
  /** Eligible to the French PEA wrapper. */
  pea?: boolean;
}

